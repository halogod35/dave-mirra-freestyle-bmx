// Decompile every function to C, one file per source module, for grepping.
//
// Output: <outDir>/<module>.c, where <module> is the source_file from the "[symbols.csv]" plate
// comment ('/' -> '__'), "lib_<x>" for library code (with "all"), or "_unassigned". Functions are written in
// VA order, each preceded by "// VA 0x........ <name>". Library functions are skipped unless the
// second argument is "all".
//
// Usage (headless, -readOnly is fine): -postScript DecompileAll.java <outDir> [all]
//@category DMBMX

import java.io.*;
import java.nio.charset.StandardCharsets;
import java.util.*;

import ghidra.app.decompiler.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.*;

public class DecompileAll extends GhidraScript {

    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 1) { printerr("usage: DecompileAll.java <outDir> [all]"); return; }
        File outDir = new File(args[0]);
        boolean all = args.length > 1 && args[1].equals("all");
        outDir.mkdirs();
        DecompInterface ifc = new DecompInterface();
        DecompileOptions opt = new DecompileOptions();
        ifc.setOptions(opt);
        ifc.toggleCCode(true);
        ifc.toggleSyntaxTree(false);
        ifc.setSimplificationStyle("decompile");
        if (!ifc.openProgram(currentProgram)) { printerr("decompiler: " + ifc.getLastMessage()); return; }

        Map<String, PrintWriter> files = new TreeMap<>();
        int n = 0, nFail = 0, nSkip = 0;
        try {
            FunctionIterator it = currentProgram.getListing().getFunctions(true);
            while (it.hasNext()) {
                monitor.checkCancelled();
                Function f = it.next();
                if (f.isExternal() || f.isThunk()) continue;
                String lib = null;
                for (FunctionTag t : f.getTags()) if (t.getName().startsWith("LIB_")) lib = t.getName().substring(4);
                if (lib != null && !all) { nSkip++; continue; }
                String module = "_unassigned";
                String plate = f.getComment();
                if (plate != null) {
                    for (String l : plate.split("\n")) {
                        int i = l.indexOf("source_file: ");
                        if (l.startsWith("[symbols.csv] ") && i >= 0) {
                            String s = l.substring(i + 13).split(" \\| ")[0].trim();
                            if (!s.isEmpty() && !s.equals("?")) module = s.replaceAll("[.]c$", "").replaceFirst("^Bmx/src/", "Bmx/Src/")
                                .replace("/", "__").replace(":", "_");
                        }
                    }
                }
                PrintWriter w = files.get(module);
                if (w == null) {
                    w = new PrintWriter(new OutputStreamWriter(new FileOutputStream(new File(outDir, module + ".c")), StandardCharsets.UTF_8));
                    w.println("// Ghidra decompilation of NgBMX.exe, module " + module + " (generated by tools/ghidra/DecompileAll.java)");
                    files.put(module, w);
                }
                w.printf("%n// VA 0x%08x %s%n", f.getEntryPoint().getOffset(), f.getName());
                DecompileResults r = ifc.decompileFunction(f, 60, monitor);
                if (r != null && r.decompileCompleted() && r.getDecompiledFunction() != null) {
                    w.print(r.getDecompiledFunction().getC());
                } else {
                    w.println("// decompilation failed: " + (r == null ? "null" : r.getErrorMessage()));
                    nFail++;
                }
                n++;
                if (n % 500 == 0) println("DecompileAll: " + n + " ...");
            }
        } finally {
            for (PrintWriter w : files.values()) w.close();
            ifc.dispose();
        }
        println(String.format("DecompileAll: %d functions in %d files, %d failed, %d library skipped -> %s",
            n, files.size(), nFail, nSkip, outDir));
    }
}
