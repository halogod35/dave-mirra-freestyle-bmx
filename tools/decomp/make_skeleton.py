def src_path(source_file: str) -> str:
    """Bmx/Src/com/x.c -> zaxis/Bmx/Src/com/x.c (relative to decomp/src)."""
    return "zaxis/" + source_file if source_file.startswith("Bmx/") else source_file


def original_path(source_file: str) -> str:
    p = source_file.replace("/", "\\")
    return "C:\\zaxis\\" + p if source_file.startswith("Bmx/") else "C:\\" + p


def parse_ghidra_c(directory):
    """{va: signature} from DecompileAll.java output."""
    sigs = {}
    for fn in sorted(os.listdir(directory)):
        if not fn.endswith(".c"):
            continue
        with open(os.path.join(directory, fn), encoding="utf-8") as f:
            lines = f.read().split("\n")
        i = 0
        while i < len(lines):
            m = re.match(r"^// VA 0x([0-9a-f]{8}) ", lines[i])
            if not m:
                i += 1
                continue
            va = int(m.group(1), 16)
            i += 1
            sig = []
            while i < len(lines) and not lines[i].startswith("{") and not lines[i].startswith("// VA "):
                t = lines[i].strip()
                if t and not t.startswith("/*") and not t.startswith("//"):
                    sig.append(t)
                i += 1
            if sig:
                sigs[va] = " ".join(sig)
    return sigs


def rename_sig(sig: str, name: str) -> str:
    """Replace the function name in a signature with `name` (Ghidra may print an older name)."""
    m = re.match(r"^(.*?)([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$", sig)
    if not m:
        return sig
    return f"{m.group(1)}{name}({m.group(3)})"


def return_type(sig: str) -> str:
    m = re.match(r"^(.*?)([A-Za-z_][A-Za-z0-9_]*)\s*\(", sig)
    if not m:
        return "void"
    ret = re.sub(r"\b__(cdecl|stdcall|fastcall|thiscall)\b", "", m.group(1)).strip()
    return ret or "int"


STUB_BODY_RE = re.compile(
    r"\n\{\n    /\* TODO\(decomp\): not decompiled yet \(see out/ghidra_c\) \*/\n(?:    return 0;\n)?\}\n")


def is_hand_written(path) -> bool:
    """True if the file holds anything but generated stubs: no generator mark, or more function
    bodies than exact stub bodies. Such a file is never overwritten or deleted, whatever the
    statuses in functions.csv say."""
    if not os.path.exists(path):
        return False
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if GEN_MARK not in text:
        return True
    return text.count("\n{\n") > len(STUB_BODY_RE.findall(text))


def stub(fn) -> str:
    sig = fn["signature"] or f"void {fn['name']}(void)"
    ret = return_type(sig)
    conf = f"[{fn['confidence']}] {fn['method']}" if fn["confidence"] else "unassigned"
    body = "    /* TODO(decomp): not decompiled yet (see out/ghidra_c) */\n"
    if ret != "void":
        body += "    return 0;\n" if "*" not in ret else "    return 0;\n"
    return (f"/* VA 0x{fn['va']:08x}, {fn['size']} bytes, {conf}, status {fn['status']} */\n"
            f"{sig}\n{{\n{body}}}\n")


def file_header(path, source_file, fns, evidence):
    orig = original_path(source_file) if source_file else "(unknown)"
    return (f"/*\n * {path}\n"
            f" * Original: {orig}\n"
            f" * Evidence: {evidence}\n"
            f" * {len(fns)} functions, {sum(f['size'] for f in fns)} bytes, "
            f"VA 0x{fns[0]['va']:08x}-0x{fns[-1]['va'] + fns[-1]['size'] - 1:08x}.\n"
            f" * {GEN_MARK}. Non-matching C (AD-8): replace each stub with\n"
            f" * readable C, keep its VA comment, set its status in decomp/functions.csv.\n"
            f" */\n#include \"decomp.h\"\n\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--functions", default=os.path.join(ROOT, "decomp", "symbols", "functions.csv"))
    ap.add_argument("--signatures", help="directory with DecompileAll.java output (out/ghidra_c)")
    ap.add_argument("--out", default=DECOMP, help="decomp directory (default: this checkout's decomp/)")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    funcs = bs.load_functions(a.functions)
    mod, code = bs.attribute(funcs, anchors=bs.load_anchors(os.path.join(ROOT, "decomp", "symbols", "symbols.csv")))
    names = {}
    with open(a.functions, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            names[int(r["va"], 16)] = r["name"]

    fcsv = os.path.join(a.out, "functions.csv")
    old = {}
    if os.path.exists(fcsv):
        with open(fcsv, encoding="utf-8", newline="") as f:
            for r in csv.DictReader(f):
                old[int(r["va"], 16)] = r
    sigs = parse_ghidra_c(a.signatures) if a.signatures else {}

    # gaps: name them by their neighbours
    order = [f["va"] for f in code]
    gapfile = {}
    i = 0
    while i < len(order):
        if order[i] in mod:
            i += 1
            continue
        j = i
        while j < len(order) and order[j] not in mod:
            j += 1
        prev = bs.stem(mod[order[i - 1]][0]) if i > 0 else "start"
        nxt = bs.stem(mod[order[j]][0]) if j < len(order) else "end"
        for va in order[i:j]:
            gapfile[va] = f"_unassigned/gap_{prev}__{nxt}.c"
        i = j

    rows = []
    for f in code:
        va = f["va"]
        o = old.get(va, {})
        name = names.get(va, f["name"])
        if va in mod:
            sf, conf, method = mod[va]
            path = src_path(sf)
        else:
            sf, conf, method, path = "", "", "gap", gapfile[va]
        sig = sigs.get(va) or o.get("signature", "")
        sig = rename_sig(sig, name) if sig else ""
        status = o.get("status", "todo") if o.get("status") in STATUSES else "todo"
        rows.append({"va": va, "size": f["size"], "name": name, "file": path, "source_file": sf,
                     "confidence": conf, "method": method, "status": status, "signature": sig})

    # functions.csv
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(HEADER)
    for r in rows:
        w.writerow(["0x%08x" % r["va"], r["size"], r["name"], r["file"], r["confidence"], r["method"],
                    r["status"], r["signature"]])
    fcsv_text = buf.getvalue()

    # source files
    byfile = OrderedDict()
    for r in rows:
        byfile.setdefault(r["file"], []).append(r)
    files = {}
    skipped = []
    for path, fns in byfile.items():
        if any(fn["status"] != "todo" for fn in fns):
            skipped.append(path)
            continue
        if is_hand_written(os.path.join(a.out, "src", path)):
            skipped.append(path)
            print(f"warning: {path} has hand-written code but its functions are all 'todo' in "
                  f"functions.csv; kept as is (set their status to draft)", file=sys.stderr)
            continue
        sf = fns[0]["source_file"]
        if not sf:
            ev = "[I] unattributed gap between two files; split it when the neighbours are decompiled"
        elif sf in bs.NEW_FILES:
            ev = "[I] new file: no path string in the exe; name invented in the original style"
        elif sf in bs.ORPHAN_PATHS:
            ev = f"[V] path string at 0x{bs.ORPHAN_PATHS[sf]:08x} (no code xref); functions [I] by its literals"
        else:
            nv = sum(fn["confidence"] == "V" for fn in fns)
            ev = f"[V] path string referenced by {nv} function(s); the others [I] (link order, literals, calls)"
        text = file_header(path, sf, fns, ev) + "\n".join(stub(fn) for fn in fns)
        files[os.path.normpath(os.path.join(a.out, "src", path))] = text

    # Kept (hand-written) files are never edited here, so report functions the attribution now puts
    # in them that have no stub yet (or stubs for functions that moved away): fix those by hand.
    for path in skipped:
        fp = os.path.join(a.out, "src", path)
        if not os.path.exists(fp):
            continue
        with open(fp, encoding="utf-8") as f:
            have = {int(x, 16) for x in re.findall(r"/\* VA 0x([0-9a-f]{8}),", f.read())}
        want = {fn["va"] for fn in byfile[path]}
        for va in sorted(want - have):
            print(f"warning: {path}: no stub for 0x{va:08x} (add it by hand)", file=sys.stderr)
        for va in sorted(have - want):
            print(f"warning: {path}: 0x{va:08x} is no longer attributed to this file (move it)", file=sys.stderr)

    # PROGRESS tables
    per = OrderedDict()
    for r in rows:
        per.setdefault(r["file"], []).append(r)
    out = io.StringIO()
    p = lambda *x: print(*x, file=out)
    total = len(rows)
    nbytes = sum(r["size"] for r in rows)
    st = Counter(r["status"] for r in rows)
    p("<!-- BEGIN GENERATED by tools/decomp/make_skeleton.py; do not edit by hand -->")
    p()
    p("### Totals")
    p()
    p(f"- Functions: **{total}** ({nbytes} bytes) in {len([k for k in per if not k.startswith('_unassigned')])} source files "
      f"+ {len([k for k in per if k.startswith('_unassigned')])} unassigned gap files.")
    p(f"- Status: todo {st['todo']}, draft {st['draft']}, reviewed {st['reviewed']}.")
    na = sum(1 for r in rows if r["confidence"])
    p(f"- Attributed to a source file: {na} ({100 * na // max(1, total)}%), of which [V] {sum(1 for r in rows if r['confidence'] == 'V')}.")
    p()
    p("### Proposed module groups")
    p()
    p("| # | Module group | Files | Functions | Bytes | Done |")
    p("|---:|---|---|---:|---:|---:|")
    used = set()
    for k, (title, srcs) in enumerate(MODULE_ORDER, 1):
        paths = [src_path(s) for s in srcs]
        fns = [r for pth in paths for r in per.get(pth, [])]
        used.update(paths)
        done = sum(r["status"] == "reviewed" for r in fns)
        names_ = ", ".join(f"`{os.path.basename(x)}`" + ("" if x in per else " (no code found)") for x in paths)
        p(f"| {k} | {title} | {names_} | {len(fns)} | {sum(r['size'] for r in fns)} | {done} |")
    rest = [pth for pth in per if pth not in used and not pth.startswith("_unassigned")]
    if rest:
        p(f"| | (not in a group yet) | {', '.join('`' + x + '`' for x in rest)} | "
          f"{sum(len(per[x]) for x in rest)} | {sum(r['size'] for x in rest for r in per[x])} | |")
    gaps = [pth for pth in per if pth.startswith("_unassigned")]
    p(f"| | (unassigned gaps) | {len(gaps)} files | {sum(len(per[x]) for x in gaps)} | "
      f"{sum(r['size'] for x in gaps for r in per[x])} | |")
    p()
    p("### Per file")
    p()
    p("| File (decomp/src/...) | Funcs | Bytes | V | I | todo/draft/reviewed |")
    p("|---|---:|---:|---:|---:|---|")
    for pth, fns in per.items():
        c = Counter(fn["status"] for fn in fns)
        p(f"| `{pth}` | {len(fns)} | {sum(fn['size'] for fn in fns)} | "
          f"{sum(fn['confidence'] == 'V' for fn in fns)} | {sum(fn['confidence'] == 'I' for fn in fns)} | "
          f"{c['todo']}/{c['draft']}/{c['reviewed']} |")
    p()
    p("<!-- END GENERATED -->")
    gen = out.getvalue()

    print(f"functions={total} bytes={nbytes} files={len(per)} written={len(files)} kept(started)={len(skipped)} "
          f"signatures={sum(1 for r in rows if r['signature'])}")
    if a.check:
        return
    with open(fcsv, "w", encoding="utf-8", newline="") as f:
        f.write(fcsv_text)
    # remove stale generated files (only ones we generated and that are no longer produced)
    srcroot = os.path.join(a.out, "src")
    wanted = {os.path.normcase(os.path.normpath(k)) for k in files}
    for dp, _, fns in os.walk(srcroot):
        for fn in fns:
            fp = os.path.join(dp, fn)
            if os.path.normcase(os.path.normpath(fp)) in wanted or not fn.endswith(".c"):
                continue
            rel = os.path.relpath(fp, srcroot).replace("\\", "/")
            if rel in skipped:
                continue
            with open(fp, encoding="utf-8") as f:
                generated = GEN_MARK in f.read(2000)
            if generated and not is_hand_written(fp):
                os.remove(fp)
    for fp, text in files.items():
        os.makedirs(os.path.dirname(fp), exist_ok=True)
        with open(fp, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    prog = os.path.join(a.out, "PROGRESS.md")
    doc = open(prog, encoding="utf-8").read() if os.path.exists(prog) else "# Decompilation progress\n\n"
    b, e = doc.find("<!-- BEGIN GENERATED"), doc.find("<!-- END GENERATED -->")
    doc = (doc[:b] + gen.rstrip("\n") + doc[e + len("<!-- END GENERATED -->"):]) if b >= 0 and e >= 0 \
        else doc.rstrip("\n") + "\n\n" + gen
    with open(prog, "w", encoding="utf-8", newline="\n") as f:
        f.write(doc)
    print(f"wrote {fcsv}, {len(files)} source files, {prog}")


if __name__ == "__main__":
    main()
