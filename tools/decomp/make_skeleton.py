"""Build the decompilation skeleton: decomp/functions.csv, decomp/src/** stubs and the
generated tables in decomp/PROGRESS.md.

    tools/testing/py.sh tools/decomp/make_skeleton.py --signatures out/ghidra_c   # refresh signatures from Ghidra C
    tools/testing/py.sh tools/decomp/make_skeleton.py                             # reuse decomp/functions.csv signatures
    tools/testing/py.sh tools/decomp/make_skeleton.py --check                     # report only

Inputs: decomp/symbols/functions.csv (Ghidra export), the module attribution of tools/ghidra/build_symbols.py,
and the signatures (from DecompileAll.java output, or the signature column of the existing
decomp/functions.csv so the skeleton can be rebuilt without out/).

Rules:
- Every non-library, non-thunk function below the library range is listed (status todo|draft|reviewed).
- A source file is (re)written only while all its functions are still `todo` AND it holds nothing
  but generated stubs (is_hand_written); otherwise the generator leaves it alone.
- Unattributed functions go to decomp/src/_unassigned/gap_<prev>__<next>.c.
- decomp/src mirrors the original tree (AD-8): Bmx/... -> decomp/src/zaxis/Bmx/...,
  NgEngine/... -> decomp/src/NgEngine/...
"""
